// Converts Frozen Bubble's level file into src/levels.ts for the sideways grid.
//
// Frozen Bubble: ceiling at the top, 8-wide hex rows, alternate rows offset by
// half a bubble and 7 wide. Here: wall on the right, so FB row y becomes the
// column y cells left of the wall and FB column x becomes screen row x. The
// offset rows round half up (x + 0.5 -> x + 1); with 8-neighbour adjacency
// each bubble still touches everything it touched in the hex layout.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(join(root, 'levels/frozen-bubble-levels.txt'), 'utf8')

const DEPTH = 10   // FB rows per level
const ROWS = 9     // screen rows available

const levels = []
for (const block of src.trim().split(/\n\s*\n/)) {
  const lines = block.split('\n').filter((l) => l.trim() !== '')
  if (lines.length !== DEPTH) throw new Error(`level ${levels.length + 1}: ${lines.length} rows`)
  const grid = Array.from({ length: ROWS }, () => Array(DEPTH).fill('.'))
  lines.forEach((line, y) => {
    const offset = line.startsWith(' ')
    const cells = line.trim().split(/\s+/)
    if (cells.length !== (offset ? 7 : 8)) throw new Error(`level ${levels.length + 1} row ${y}: ${cells.length} cells`)
    cells.forEach((c, x) => {
      if (c === '-') return
      const row = offset ? x + 1 : x
      grid[row][y] = String(Number(c) + 1) // 1..8; 0 is empty in the game
    })
  })
  levels.push(grid.map((r) => r.join('')))
}

const out = [
  '// Generated by scripts/convert-levels.mjs from levels/frozen-bubble-levels.txt.',
  '// Frozen Bubble level data, GPL-2.0, see levels/README.md. Do not edit by hand.',
  '//',
  `// Each level is ${ROWS} screen rows of ${DEPTH} columns; column 0 touches the wall.`,
  "// '.' empty, '1'..'8' bubble type.",
  'export const LEVEL_DEPTH = ' + DEPTH,
  'export const LEVELS: readonly (readonly string[])[] = [',
  ...levels.map((l) => '  [' + l.map((r) => `'${r}'`).join(', ') + '],'),
  ']',
  '',
]
writeFileSync(join(root, 'src/levels.ts'), out.join('\n'))
console.log(`wrote ${levels.length} levels`)
